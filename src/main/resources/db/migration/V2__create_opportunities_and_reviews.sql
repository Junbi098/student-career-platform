CREATE TABLE opportunities (
    id UUID PRIMARY KEY,
    version BIGINT NOT NULL,
    duplicate_key VARCHAR(64) NOT NULL UNIQUE,
    company_dossier_id UUID NOT NULL REFERENCES company_dossiers(id),
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    opportunity_type VARCHAR(32) NOT NULL CHECK (opportunity_type IN ('INTERNSHIP','JUNIOR_JOB')),
    description TEXT NOT NULL,
    sector VARCHAR(200),
    location VARCHAR(300),
    work_mode VARCHAR(32) NOT NULL CHECK (work_mode IN ('ON_SITE','HYBRID','REMOTE','UNKNOWN')),
    published_on DATE,
    deadline_at TIMESTAMP WITH TIME ZONE,
    deadline_precision VARCHAR(16) NOT NULL CHECK (deadline_precision IN ('DATE','TIME','UNKNOWN')),
    source_url TEXT NOT NULL,
    source_title VARCHAR(300) NOT NULL,
    external_reference VARCHAR(128),
    application_url TEXT,
    mauritian_eligibility VARCHAR(16) NOT NULL CHECK (mauritian_eligibility IN ('YES','NO','UNKNOWN')),
    international_eligibility VARCHAR(16) NOT NULL CHECK (international_eligibility IN ('YES','NO','UNKNOWN')),
    eligibility_details VARCHAR(2000),
    origin VARCHAR(32) NOT NULL CHECK (origin IN ('MANUAL_ENTRY','HTML_SUBMISSION')),
    verification VARCHAR(32) NOT NULL CHECK (verification IN ('UNVERIFIED','CONFIRMED','REJECTED')),
    closed BOOLEAN NOT NULL,
    first_submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_verified_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT verification_date_consistency CHECK (
        (verification = 'UNVERIFIED' AND last_verified_at IS NULL) OR
        (verification <> 'UNVERIFIED' AND last_verified_at IS NOT NULL)
    ),
    CONSTRAINT deadline_consistency CHECK ((deadline_at IS NULL) = (deadline_precision = 'UNKNOWN')),
    CONSTRAINT eligibility_evidence CHECK (
        (mauritian_eligibility = 'UNKNOWN' AND international_eligibility = 'UNKNOWN') OR
        coalesce(length(trim(eligibility_details)), 0) > 0
    )
);
CREATE INDEX opportunity_company_idx ON opportunities(company_dossier_id);
CREATE INDEX opportunity_deadline_idx ON opportunities(deadline_at);
CREATE TABLE opportunity_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id UUID NOT NULL REFERENCES opportunities(id),
    action VARCHAR(32) NOT NULL CHECK (action IN ('SUBMITTED','CONFIRM','REJECT','CLOSE','REOPEN','MATERIAL_CHANGE')),
    notes VARCHAR(2000) NOT NULL,
    evidence_url TEXT,
    source_reviewed BOOLEAN NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    opportunity_version BIGINT NOT NULL,
    CONSTRAINT manual_confirmation_evidence CHECK (
        action NOT IN ('CONFIRM','REJECT') OR (source_reviewed AND evidence_url IS NOT NULL)
    )
);
CREATE INDEX opportunity_reviews_lookup_idx ON opportunity_reviews(opportunity_id, id);
